export const humanize = (value) =>
  String(value || "unavailable").replaceAll("_", " ");
export function auditDetails(event) {
  const value = event.detail ?? event.details ?? {};
  if (typeof value === "object" && value !== null) return value;
  try {
    return JSON.parse(value);
  } catch {
    return {};
  }
}
export function validationFor(incident, step) {
  const events = (incident?.audit || []).filter(
    (e) =>
      ["validation", "validation_rejected", "error"].includes(e.action) &&
      auditDetails(e).step === step,
  );
  const last = events.at(-1);
  if (!last) return { label: "Not recorded", tone: "neutral" };
  const details = auditDetails(last);
  return last.action === "validation" && details.status === "passed"
    ? { label: "Validation passed", tone: "success" }
    : { label: "Failure recorded", tone: "danger" };
}
export function generation(mode) {
  return (
    {
      nemotron: ["Generated by Nemotron", "success"],
      fallback: ["Source-only fallback", "warning"],
      unknown: ["Provenance unavailable", "neutral"],
    }[mode] || ["Provenance unavailable", "neutral"]
  );
}
export function intelligenceState(intelligence, provenance) {
  const limitations = intelligence?.limitations || [];
  if (limitations.includes("No relevant source was retrieved."))
    return ["No relevant sources retrieved", "warning"];
  if (provenance?.mode) return generation(provenance.mode);
  if (limitations.some((text) => text.includes("AI summary unavailable")))
    return generation("fallback");
  return generation("unknown");
}
export function safeJson(value, fallback = null) {
  if (typeof value !== "string") return value ?? fallback;
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}
export function eventTime(value) {
  if (!value) return "Time not recorded";
  const normalized = /(?:Z|[+-]\d\d:\d\d)$/.test(value)
    ? value
    : value.replace(" ", "T") + "Z";
  const date = new Date(normalized);
  return Number.isNaN(date.getTime())
    ? "Time unavailable"
    : date.toLocaleString("en-US", {
        month: "short",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        timeZone: "UTC",
      }) + " UTC";
}
export function assetCount(item) {
  const ids = item?.affected_asset_ids ?? item?.detection?.affected_asset_ids;
  return Array.isArray(ids) ? ids.length : null;
}
