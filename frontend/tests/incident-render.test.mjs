import assert from 'node:assert/strict';
import test from 'node:test';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';

// Load the actual JSX with Vite, then render the API's structured intelligence.
// This catches React's "Objects are not valid as a React child" regression.
test('incident renders structured Agent 3 guidance and legacy text', async () => {
  const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
  try {
    const { default: IncidentDetail } = await server.ssrLoadModule('/src/IncidentDetail.jsx');
    const incident = {
      incident_id: 'INC-001', severity: 'high', approval_status: 'pending',
      mitre_techniques: [{ technique_id: 'T1078', name: 'Valid Accounts' }],
      recommended_actions: [{ action: 'Review expired permissions.', source_document_ids: ['POL-003'] }],
      policy_references: [{ policy_id: 'POL-003', section: 'Expired Permissions', summary: 'Review access.', source_document_ids: ['POL-003'] }],
      recipients: [],
    };
    const render = data => renderToStaticMarkup(React.createElement(IncidentDetail, { incident: data, user: { role: 'viewer' } }));
    const html = render(incident);
    for (const expected of ['T1078', 'Valid Accounts', 'Review expired permissions.', 'POL-003', 'Expired Permissions']) {
      assert.ok(html.includes(expected), expected);
    }
    const legacy = render({ ...incident, recommended_actions: ['Review access.'], policy_references: ['POL-001'], mitre_techniques: [{ id: 'T1078', name: 'Valid Accounts' }] });
    assert.ok(legacy.includes('Review access.') && legacy.includes('POL-001'));
  } finally {
    await server.close();
  }
});


test('workflow explorer separates saved provenance from a live connection check', async () => {
  const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
  try {
    const { default: DemoPanel } = await server.ssrLoadModule('/src/DemoPanel.jsx');
    const render = incident => renderToStaticMarkup(React.createElement(DemoPanel, { incident, user: { role: 'reviewer' } }));
    const incident = { incident_id: 'INC-001', intelligence: { limitations: ['AI summary unavailable; showing retrieved sources only.'] }, ai_generation: { mode: 'fallback' } };
    const html = render(incident);
    assert.ok(html.includes('Saved report: Source-only fallback'));
    assert.ok(html.includes('Test Nemotron') && html.includes('Generate AI preview'));
    assert.ok(html.includes('Not checked.') && !html.includes('Live inference verified'));
    assert.ok(html.includes('Explore source references') && html.includes('AI summary unavailable'));
    assert.ok(render({ ...incident, ai_generation: undefined }).includes('Generation not recorded'));
    assert.ok(render({ ...incident, ai_generation: { mode: 'nemotron' } }).includes('Saved report: Generated by Nemotron'));
  } finally { await server.close(); }
});
