import test, { after, before } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { createServer } from "vite";
import {
  validationFor,
  intelligenceState,
  assetCount,
  eventTime,
} from "../src/model.js";
const incident = JSON.parse(
  readFileSync(new URL("./fixtures/incident.json", import.meta.url)),
);
let server;
before(async () => {
  server = await createServer({
    optimizeDeps: { noDiscovery: true, include: [] },
    server: { middlewareMode: true, hmr: false, ws: false },
    appType: "custom",
  });
});
after(async () => {
  await server.close();
});
async function render(module, name, props) {
  const component = (await server.ssrLoadModule(module))[name];
  return renderToStaticMarkup(React.createElement(component, props));
}

test("real captured detection shows triggers, initial severity and evidence", async () => {
  const html = await render("/src/components/AgentViews.jsx", "DetectionView", {
    incident,
  });
  for (const value of [
    "R1",
    "R2",
    "R4",
    "admin_04",
    "198.51.100.24",
    "LOG-101",
    "LOG-105",
  ])
    assert.ok(html.includes(value), value);
  assert.ok(!html.includes("R3</code>"));
});
test("investigation exposes permission distinctions, confidence and hypotheses", async () => {
  const html = await render(
    "/src/components/AgentViews.jsx",
    "InvestigationView",
    { incident },
  );
  for (const value of [
    "Authorized",
    "Expired",
    "No permission",
    "90%",
    "Hypotheses",
    "Benign explanations",
    "LOG-103",
  ])
    assert.ok(html.includes(value), value);
  const old = await render(
    "/src/components/AgentViews.jsx",
    "InvestigationView",
    { incident: { investigation: { severity: "high" } } },
  );
  assert.ok(
    old.includes("Timeline not recorded") &&
      old.includes("Asset authorization details not recorded") &&
      old.includes("Not recorded"),
  );
  assert.ok(!old.includes("90%"));
});
test("validation is derived from actual audit rather than data presence", async () => {
  assert.equal(
    validationFor(incident, "investigation").label,
    "Validation passed",
  );
  assert.equal(
    validationFor({ ...incident, audit: [] }, "investigation").label,
    "Not recorded",
  );
  assert.equal(
    validationFor(
      {
        ...incident,
        audit: [{ action: "error", detail: { step: "investigation" } }],
      },
      "investigation",
    ).tone,
    "danger",
  );
  const html = await render(
    "/src/components/AgentViews.jsx",
    "ValidationView",
    { incident: { status: "incomplete", audit: [] } },
  );
  assert.ok(
    html.includes("No validation events recorded") &&
      html.includes("incomplete"),
  );
});
test("provenance distinguishes no sources, fallback and unrecorded modes", () => {
  assert.equal(intelligenceState({}, null)[0], "Provenance unavailable");
  assert.equal(
    intelligenceState(
      {
        limitations: [
          "AI summary unavailable; showing retrieved sources only.",
        ],
      },
      null,
    )[0],
    "Source-only fallback",
  );
  assert.equal(
    intelligenceState(
      { limitations: ["No relevant source was retrieved."] },
      { mode: "fallback" },
    )[0],
    "No relevant sources retrieved",
  );
  assert.equal(
    intelligenceState({}, { mode: "nemotron" })[0],
    "Generated by Nemotron",
  );
  assert.equal(assetCount({}), null);
  assert.notEqual(eventTime("2026-11-07T09:10:00Z"), "Time unavailable");
});
test("intelligence separates connection, saved provenance and preview labels", async () => {
  const html = await render("/src/components/IntelligenceView.jsx", "default", {
    incident,
    reviewer: true,
    connection: {
      verified: true,
      message: "Live JSON inference verified.",
      checked_at: "2026-11-08T00:00:00Z",
      latency_ms: 100,
    },
    preview: {
      mode: "fallback",
      intelligence: { limitations: ["No relevant source was retrieved."] },
    },
  });
  assert.ok(html.includes("Live inference verified"));
  assert.ok(
    html.includes("Source-only fallback") &&
      html.includes("No relevant sources retrieved"),
  );
  assert.ok(!html.includes("Generated by Nemotron"));
});
test("notification controls respect decision and show mock delivery accurately", async () => {
  const props = {
    incident: { ...incident, approval_status: "rejected" },
    reviewer: true,
  };
  const rejected = await render(
    "/src/components/NotificationView.jsx",
    "default",
    props,
  );
  assert.ok(
    rejected.includes("Notifications rejected") &&
      !rejected.includes("Approve incident</button>"),
  );
  const viewer = await render(
    "/src/components/NotificationView.jsx",
    "default",
    { ...props, incident, reviewer: false },
  );
  assert.ok(
    viewer.includes("Read-only viewer") &&
      !viewer.includes("Approve incident</button>"),
  );
  const mocked = await render(
    "/src/components/NotificationView.jsx",
    "default",
    {
      ...props,
      incident: {
        ...incident,
        recipients: [
          {
            recipient_id: "EMP-test",
            status: "mocked",
            asset_ids: ["ASSET-test"],
            display_name: "Test owner",
          },
        ],
      },
    },
  );
  assert.ok(
    mocked.includes("Mock sent · simulated") &&
      mocked.includes("No real message was sent"),
  );
});
